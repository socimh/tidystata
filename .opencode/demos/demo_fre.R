# Demo: fre() function
# Shows actual output of fre() for frequency tables with totals

library(dplyr)

pkgload::load_all(".", quiet = TRUE, compile = FALSE)

cat("## Example 1: Basic frequency with Total\n\n")
cat("```r\n")
cat("fre(mtcars, cyl)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(fre(mtcars, cyl))
cat("```\n\n")

cat("## Example 2: With tibble output\n\n")
cat("```r\n")
cat("fre(mtcars, cyl, .type = 'tibble')\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(fre(mtcars, cyl, .type = "tibble"))
cat("```\n\n")

cat("## Example 3: With grouping\n\n")
cat("```r\n")
cat("fre(mtcars, gear, .by = cyl, .type = 'tibble')\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(fre(mtcars, gear, .by = cyl, .type = "tibble"))
cat("```\n\n")

cat("## Example 4: With starwars data\n\n")
cat("```r\n")
cat("fre(starwars, sex, .type = 'tibble')\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(fre(starwars, sex, .type = "tibble"))
cat("```\n\n")

cat("## Example 5: With missing values\n\n")
cat("```r\n")
cat("df <- data.frame(x = c('a', 'b', NA, 'a', 'b', NA))\n")
cat("fre(df, x, .type = 'tibble')\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
df <- data.frame(x = c("a", "b", NA, "a", "b", NA))
print(fre(df, x, .type = "tibble"))
cat("```\n\n")

cat("## Example 6: fre1() for multiple variables\n\n")
cat("```r\n")
cat("fre1(starwars, sex, gender, .type = 'tibble')\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(fre1(starwars, sex, gender, .type = "tibble"))
cat("```\n\n")
