# Demo: summ() function
# Shows actual output of summ() for numeric variables

library(dplyr)
library(tibble)

library(statart)

cat("## Example 1: Basic numeric summary\n\n")
cat("```r\n")
cat("summ(mtcars, mpg)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(summ(mtcars, mpg))
cat("```\n\n")

cat("## Example 2: Multiple variables\n\n")
cat("```r\n")
cat("summ(mtcars, mpg, hp, wt)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(summ(mtcars, mpg, hp, wt))
cat("```\n\n")

cat("## Example 3: Grouped summary\n\n")
cat("```r\n")
cat("summ(mtcars, mpg, .by = cyl)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(summ(mtcars, mpg, .by = cyl))
cat("```\n\n")

cat("## Example 4: Custom statistics\n\n")
cat("```r\n")
cat("summ(mtcars, mpg, .stat = c('mean', 'sd'))\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(summ(mtcars, mpg, .stat = c("mean", "sd")))
cat("```\n\n")

cat("## Example 5: Detailed statistics\n\n")
cat("```r\n")
cat("summ(mtcars, mpg, .detail = TRUE)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(summ(mtcars, mpg, .detail = TRUE))
cat("```\n\n")

cat("## Example 6: Inf/-Inf handling\n\n")
cat("```r\n")
cat("summ(data.frame(x = c(1, 2, Inf, -Inf, 3)))\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(summ(data.frame(x = c(1, 2, Inf, -Inf, 3))))
cat("```\n\n")

cat("## Example 7: With grouping and NA handling\n\n")
cat("```r\n")
cat("df <- data.frame(x = c(1, 2, 3, 4), g = c('a', 'a', NA, 'b'))\n")
cat("summ(df, .by = g, .missing = FALSE)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
df <- data.frame(x = c(1, 2, 3, 4), g = c("a", "a", NA, "b"))
print(summ(df, .by = g, .missing = FALSE))
cat("```\n\n")

cat("## Example 8: All numeric variables\n\n")
cat("```r\n")
cat("summ(mtcars[, 1:4])\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(summ(mtcars[, 1:4]))
cat("```\n\n")

cat("## Example 9: tabstat() wrapper\n\n")
cat("```r\n")
cat("tabstat(mtcars, .by = cyl)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tabstat(mtcars, .by = cyl))
cat("```\n\n")

cat("## Example 10: Zero-variance column\n\n")
cat("```r\n")
cat("summ(data.frame(x = rep(5, 10)))\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(summ(data.frame(x = rep(5, 10))))
cat("```\n\n")
