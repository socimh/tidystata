# Demo: tab1() function
# Shows actual output of tab1() for one-way frequency tables

library(dplyr)

library(statart)

cat("## Example 1: Basic one-way table\n\n")
cat("```r\n")
cat("tab1(starwars, sex)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab1(starwars, sex))
cat("```\n\n")

cat("## Example 2: Multiple variables\n\n")
cat("```r\n")
cat("tab1(starwars, sex, gender)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab1(starwars, sex, gender))
cat("```\n\n")

cat("## Example 3: With boolean expression\n\n")
cat("```r\n")
cat("tab1(starwars, tall = height > 180)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab1(starwars, tall = height > 180))
cat("```\n\n")

cat("## Example 4: With tibble output\n\n")
cat("```r\n")
cat("tab1(starwars, sex, gender, .type = 'tibble')\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab1(starwars, sex, gender, .type = "tibble"))
cat("```\n\n")

cat("## Example 5: With tidyselect\n\n")
cat("```r\n")
cat("tab1(starwars, ends_with('color'))\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab1(starwars, ends_with("color")))
cat("```\n\n")

cat("## Example 6: Named expression\n\n")
cat("```r\n")
cat("tab1(starwars, human = species == 'Human')\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab1(starwars, human = species == "Human"))
cat("```\n\n")
