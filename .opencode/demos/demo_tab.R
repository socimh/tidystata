# Demo: tab() function
# Shows actual output of tab() for frequency tables

library(dplyr)
library(tibble)

library(tidystata)

cat("## Example 1: Basic frequency table\n\n")
cat("```r\n")
cat("tab(mtcars, cyl)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab(mtcars, cyl))
cat("```\n\n")

cat("## Example 2: With percentages\n\n")
cat("```r\n")
cat("tab(mtcars, cyl)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab(mtcars, cyl))
cat("```\n\n")

cat("## Example 3: Sorted by frequency (descending)\n\n")
cat("```r\n")
cat("tab(mtcars, cyl, .desc = TRUE)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab(mtcars, cyl, .desc = TRUE))
cat("```\n\n")

cat("## Example 4: With grouping\n\n")
cat("```r\n")
cat(
  "df <- data.frame(x = c('a', 'b', NA, 'a', 'b', NA), g = c('x', 'x', 'x', 'y', 'y', 'y'))\n"
)
cat("tab(df, x, .by = g)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
df <- data.frame(
  x = c("a", "b", NA, "a", "b", NA),
  g = c("x", "x", "x", "y", "y", "y")
)
print(tab(df, x, .by = g))
cat("```\n\n")

cat("## Example 5: With dplyr::starwars data\n\n")
cat("```r\n")
cat("tab(dplyr::starwars, sex)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab(dplyr::starwars, sex))
cat("```\n\n")

cat("## Example 6: Multiple variables\n\n")
cat("```r\n")
cat("tab(dplyr::starwars, sex, gender)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab(dplyr::starwars, sex, gender))
cat("```\n\n")

cat("## Example 7: With boolean expression\n\n")
cat("```r\n")
cat("tab(dplyr::starwars, tall = height > 180)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab(dplyr::starwars, tall = height > 180))
cat("```\n\n")

cat("## Example 8: Cross-tabulation (tab2)\n\n")
cat("```r\n")
cat("tab2(dplyr::starwars, sex, gender)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tab2(dplyr::starwars, sex, gender))
cat("```\n\n")
