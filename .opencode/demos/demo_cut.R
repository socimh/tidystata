# Demo: cut_quantile() function
# Shows actual output of cut_quantile() for binning data

library(dplyr)

pkgload::load_all(".", quiet = TRUE, compile = FALSE)

cat("## Example 1: Quartiles\n\n")
cat("```r\n")
cat("x <- 1:100\n")
cat("cut_quantile(x, n = 4)\n")
cat("table(cut_quantile(x, n = 4))\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
x <- 1:100
print(table(cut_quantile(x, n = 4)))
cat("```\n\n")

cat("## Example 2: Deciles\n\n")
cat("```r\n")
cat("x <- rnorm(1000)\n")
cat("table(cut_quantile(x, n = 10))\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
x <- rnorm(1000)
print(table(cut_quantile(x, n = 10)))
cat("```\n\n")

cat("## Example 3: With ties\n\n")
cat("```r\n")
cat("x <- c(rep(1, 40), rep(2, 60))\n")
cat("table(cut_quantile(x, n = 2))\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
x <- c(rep(1, 40), rep(2, 60))
print(table(cut_quantile(x, n = 2)))
cat("```\n\n")

cat("## Example 4: With NA values\n\n")
cat("```r\n")
cat("x <- c(1:98, NA, NA)\n")
cat("table(cut_quantile(x, n = 4), useNA = 'ifany')\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
x <- c(1:98, NA, NA)
print(table(cut_quantile(x, n = 4), useNA = "ifany"))
cat("```\n\n")

cat("## Example 5: Custom labels\n\n")
cat("```r\n")
cat("x <- 1:12\n")
cat("cut_quantile(x, n = 3, labels = c('low', 'mid', 'high'))\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
x <- 1:12
print(cut_quantile(x, n = 3, labels = c("low", "mid", "high")))
cat("```\n\n")

cat("## Example 6: cut_length() for equal-width bins\n\n")
cat("```r\n")
cat("x <- 1:20\n")
cat("table(cut_length(x, n = 4))\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
x <- 1:20
print(table(cut_length(x, n = 4)))
cat("```\n\n")

cat("## Example 7: cut_breaks() for custom breaks\n\n")
cat("```r\n")
cat("x <- 1:20\n")
cat("cut_breaks(x, breaks = c(5, 15))\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
x <- 1:20
print(table(cut_breaks(x, breaks = c(5, 15))))
cat("```\n\n")
