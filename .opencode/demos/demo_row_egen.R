cat("## Example 7: In mutate context\n\n")
cat("```r\n")
cat("df |>\n")
cat("  mutate(\n")
cat("    min_val = row_min(a, b, c),\n")
cat("    max_val = row_max(a, b, c)\n")
cat("  )\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(
  df |>
    mutate(
      min_val = row_min(a, b, c),
      max_val = row_max(a, b, c)
    )
)
cat("```\n\n")

cat("## Example 8: With scalar values\n\n")
