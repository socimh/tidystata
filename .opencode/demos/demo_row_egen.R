# Demo: row functions (row_min, row_max, row_mean, row_sum, row_miss, row_non_miss)
# Shows actual output of row-wise operations

library(dplyr)
library(tibble)

library(statart)

cat("## Example 1: row_min\n\n")
cat("```r\n")
cat("df <- tibble(a = c(1, 2, 3), b = c(3, 2, 1), c = c(2, 3, 1))\n")
cat("row_min(df)\n")
cat("```\n\n")

cat("**Output:**\n\n")
cat("```\n")
df <- tibble(a = c(1, 2, 3), b = c(3, 2, 1), c = c(2, 3, 1))
print(row_min(df))
cat("```\n\n")

cat("## Example 2: row_max\n\n")
cat("```r\n")
cat("row_max(df)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(row_max(df))
cat("```\n\n")

cat("## Example 3: row_mean\n\n")
cat("```r\n")
cat("row_mean(df)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(row_mean(df))
cat("```\n\n")

