# Demo: timer() function
# Shows actual output of timer() for timing code execution

library(dplyr)

library(tidystata)

cat("## Example 1: Basic timing\n\n")
cat("```r\n")
cat("timer(Sys.sleep(0.5))\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
timer(Sys.sleep(0.5))
cat("```\n\n")

cat("## Example 2: Timing with return value\n\n")
cat("```r\n")
cat("result <- timer(mean(1:1000000))\n")
cat("result\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
result <- timer(mean(1:1000000))
cat("```\n\n")
cat("**Return value:**\n\n")
cat("```\n")
print(result)
cat("```\n\n")

cat("## Example 3: Quick operation\n\n")
cat("```r\n")
cat("timer(1 + 1)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
timer(1 + 1)
cat("```\n\n")

cat("## Example 4: With pipe operations\n\n")
cat("```r\n")
cat("result <- mtcars |> filter(cyl == 4) |> timer()\n")
cat("nrow(result)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
result <- mtcars |> filter(cyl == 4) |> timer()
cat("```\n\n")
cat("**Return value (nrow):**\n\n")
cat("```\n")
print(nrow(result))
cat("```\n\n")

cat("## Example 5: Multiple operations\n\n")
cat("```r\n")
cat("timer({\n")
cat("  x <- rnorm(10000)\n")
cat("  mean(x)\n")
cat("  sd(x)\n")
cat("})\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
timer({
  x <- rnorm(10000)
  mean(x)
  sd(x)
})
cat("```\n\n")

cat("## Example 6: Internal duration formatting helper\n\n")
cat("```r\n")
cat("tidystata:::duration_to_chr(0.05)   # Sub-second\n")
cat("tidystata:::duration_to_chr(5.23)   # Seconds\n")
cat("tidystata:::duration_to_chr(75)     # Minutes\n")
cat("tidystata:::duration_to_chr(3700)   # Hours\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
print(tidystata:::duration_to_chr(0.05))
print(tidystata:::duration_to_chr(5.23))
print(tidystata:::duration_to_chr(75))
print(tidystata:::duration_to_chr(3700))
cat("```\n\n")
