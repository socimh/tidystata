def quote(value):
    return json.dumps(value, ensure_ascii=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--render-only', action='store_true')
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    if not args.render_only:
        paths = json.loads((ROOT / '.opencode/results/tabulation-accepted-paths.json').read_text(encoding='utf-8'))
        for name in ['R/summ.R', 'R/summ-helpers.R', 'R/tab.R', 'R/tab-helpers.R', 'R/type_conversion.R']:
            assert (ROOT/name).read_bytes() == (Path(paths['source'])/name).read_bytes(), name
        source = ['# Generated by .opencode/workflows/build_console_showcase.py; edit that source.',
                  '# Selective showcase: run in order from the repository root.',
                  '# Print options match the PDF: all rows, 88 columns, four significant digits.',
                  'options(width = 88, tibble.width = 88, pillar.width = 88,',
                  '        tibble.print_max = Inf, tibble.print_min = Inf,',
                  '        pillar.sigfig = 4, cli.unicode = FALSE, crayon.enabled = FALSE)', '']
        for i, page in enumerate(PAGES, 1):
            source += [f'# SECTION {i:02d}: {page["title"]}', page['code'], '']
        SOURCE.write_text('\n'.join(source), encoding='utf-8')
        (OUT/'capture.R').write_text(CAPTURE, encoding='utf-8')
        env = os.environ.copy()
        env.update(LC_ALL='C', LANG='C', NO_COLOR='1')
        with (OUT/'execution.log').open('w', encoding='utf-8') as stream:
            result = subprocess.run(['python', 'C:/Users/socimh/.codex/scripts/run_r_safe.py', '--',
                                     'Rscript', str(OUT/'capture.R'), paths['library']], cwd=ROOT,
                                    env=env, stdout=stream, stderr=subprocess.STDOUT)
        log = (OUT/'execution.log').read_text(encoding='utf-8')
        if result.returncode:
            raise RuntimeError(log[-6000:])
        assert 'SHOWCASE VERIFIED 4 sections' in log and 'R launcher exit: 0x00000000' in log
    document = [HEADER]
    for i, page in enumerate(PAGES, 1):
        if i > 1:
            document.append('#pagebreak()')
        output = (OUT/f'console-{i:02d}.txt').read_text(encoding='utf-8').rstrip()
        assert output
        document += ['#v(3mm)', '#text(size: 9pt, weight: "bold", fill: teal, ' + quote(page['tag']) + ')',
                     '#v(4mm)', '#text(size: 24pt, weight: "bold", ' + quote(page['title']) + ')',
                     '#v(3mm)', '#text(' + quote(page['purpose']) + ')',
                     '#panel("R INPUT", ' + quote(page['code']) + ', script: true)',
                     '#panel("CONSOLE OUTPUT", ' + quote(output) + ')',
                     '#hint(' + quote(page['note']) + ')']
        if i == 1:
            document += ['#v(6pt)', '#text(size: 8pt, fill: muted)[Print settings: 88 columns, all rows, four significant digits, plain text. Executed on Windows R 4.6.0; console spacing is preserved.]']
    tex = OUT/'showcase.typ'
    tex.write_text('\n'.join(document), encoding='utf-8')
    subprocess.run(['typst', 'compile', '--root', str(ROOT), str(tex), str(PDF)], cwd=ROOT, check=True)
    subprocess.run(['pdftotext', '-layout', str(PDF), str(OUT/'extracted.txt')], check=True)
    extracted = (OUT/'extracted.txt').read_text(encoding='utf-8')
    pages = [p for p in extracted.split('\f') if p.strip()]
    assert len(pages) == 4, f'Expected 4 pages; found {len(pages)}. Inspect overflow.'
    for i, page in enumerate(PAGES):
        assert page['title'] in pages[i], (i, page['title'])
        assert 'R INPUT' in pages[i] and 'CONSOLE OUTPUT' in pages[i], i
    assert '\ufffd' not in extracted
    subprocess.run(['pdftoppm', '-scale-to', '1400', '-png', str(PDF), str(OUT/'page')], check=True)
    manifest = dict(pdf=str(PDF), pages=len(pages), examples=4,
                    sha256=hashlib.sha256(PDF.read_bytes()).hexdigest(),
                    verification='Protected R exit0; no unexpected diagnostics; CSV values/shape verified',
                    source=str(SOURCE))
    (OUT/'manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    report = ROOT / '.opencode/reports/project_status_console_showcase_2026-10-16.md'
    report.write_text('\n'.join([
        '# Selective console showcase', '',
        'Created 2026-10-16 for visual review; package 0.2.0.9000.', '',
        '[Open the four-page PDF](../results/console-showcase/statart_console_showcase.pdf)', '',
        'The PDF shows a shared fictional survey, summ/tabstat numeric summaries,',
        'tab and fre2 category tables, and a joined respondent-level pipeline with CSV export.',
        'Examples are selective; this is not an exhaustive function catalogue.', '',
        'Input source: [.opencode/demos/showcase_console.R](../demos/showcase_console.R).',
        'Canonical authoring source: [build_console_showcase.py](../workflows/build_console_showcase.py).',
        'The R script is generated from the authoring source. Edit that source, then regenerate.', '',
        'Verification: protected R launcher exit0; all four sections execute without unexpected',
        'warnings/messages. The join preserves eight rows, regional counts/means are independently',
        'asserted, and exported CSV values/shape are verified after readback.',
        'The PDF has four pages, input/output panels stay together, text extraction passes,',
        'and all four rendered pages were visually reviewed for clipping, spacing and legibility.', '',
        'No package functions, dependencies, exports or previous test results changed.',
        'The accepted package baseline remains 14255 passing expectations, 22 unrelated warnings,',
        'one existing empty skip, and R CMD check Status OK. No new full-suite claim is made.', '',
        'Regenerate with `python .opencode/workflows/build_console_showcase.py` after',
        'creating the fresh installed library using verify_package.py with prefix',
        '`.opencode/results/tabulation-accepted`. Rendering only can use `--render-only`.',
        'Generated console captures, Typst source, PNGs and logs remain preserved locally.',
    ]) + '\n', encoding='utf-8')
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    main()
