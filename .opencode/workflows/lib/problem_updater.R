#' Problem Updater for Automated esttab Testing
#' 
#' Automatically updates PROBLEMS.md with new issues

library(jsonlite)

#' Read existing PROBLEMS.md and extract current esttab issues
#' 
#' @param problems_file Path to PROBLEMS.md
#' @return List of existing issue numbers and signatures
get_existing_issues <- function(problems_file = ".opencode/PROBLEMS.md") {
  if (!file.exists(problems_file)) {
    return(list(max_number = 0, signatures = character()))
  }
  
  content <- readLines(problems_file)
  
  # Find esttab-related issue numbers
  esttab_pattern <- "^### 1\\.\\d+\\."  # Assumes esttab is section 1
  esttab_lines <- grep(esttab_pattern, content, value = TRUE)
  
  issue_nums <- numeric()
  for (line in esttab_lines) {
    num <- as.numeric(sub("^### 1\\.(\\d+)\\..*", "\\1", line))
    if (!is.na(num)) issue_nums <- c(issue_nums, num)
  }
  
  max_num <- if (length(issue_nums) > 0) max(issue_nums) else 0
  
  # Extract signatures from AUTO-GENERATED entries
  sig_pattern <- "Signature: ([a-f0-9]+)"
  sig_matches <- gregexpr(sig_pattern, content, perl = TRUE)
  signatures <- character()
  for (i in seq_along(content)) {
    if (sig_matches[[i]][1] != -1) {
      m <- regmatches(content[i], sig_matches[i])[[1]]
      sig <- sub("Signature: ", "", m)
      signatures <- c(signatures, sig)
    }
  }
  
  list(max_number = max_num, signatures = signatures)
}

#' Generate markdown entry for a new issue
#' 
#' @param error_entry Error information from log
#' @param issue_number Sequential issue number
#' @return Markdown formatted string
generate_issue_entry <- function(error_entry, issue_number) {
  severity_emoji <- switch(error_entry$severity,
    "HIGH" = "🔴",
    "MEDIUM" = "🟡", 
    "LOW" = "🟢",
    "⚪"
  )
  
  sprintf('
%s
### 1.%d. [%s Error] %s - Scenario: %s
**Status**: OPEN (Auto-detected)
**Severity**: %s
**Category**: %s
**Date Detected**: %s
**Signature**: %s

**Error Message**:
```
%s
```

**Test Code**:
```r
%s
```

**Scenario Description**: %s

[This issue was auto-generated by the esttab testing workflow.]
', 
    severity_emoji,
    issue_number,
    error_entry$category,
    severity_emoji,
    error_entry$scenario_id,
    error_entry$severity,
    error_entry$category,
    error_entry$timestamp,
    error_entry$signature,
    error_entry$error_message,
    error_entry$test_code,
    error_entry$description
  )
}

#' Update PROBLEMS.md with new errors
#' 
#' @param log_file Path to error log JSON
#' @param problems_file Path to PROBLEMS.md
#' @return Number of new issues added
update_problems_md <- function(log_file = ".opencode/reports/esttab_error_log.json",
                               problems_file = ".opencode/PROBLEMS.md") {
  
  if (!file.exists(log_file)) {
    message("No error log found. Skipping PROBLEMS.md update.")
    return(0)
  }
  
  # Read error log
  log_data <- fromJSON(log_file, flatten = FALSE)
  
  # Get only NEW errors
  new_errors <- Filter(function(e) e$status == "NEW", log_data$errors)
  
  if (length(new_errors) == 0) {
    message("No new errors to add to PROBLEMS.md")
    return(0)
  }
  
  # Get existing issues info
  existing <- get_existing_issues(problems_file)
  
  # Filter out duplicates
  truly_new <- Filter(function(e) !(e$signature %in% existing$signatures), new_errors)
  
  if (length(truly_new) == 0) {
    message("All errors are already documented in PROBLEMS.md")
    # Mark as processed in log
    update_error_status(log_file, new_errors, "DOCUMENTED")
    return(0)
  }
  
  # Read current PROBLEMS.md
  if (file.exists(problems_file)) {
    content <- readLines(problems_file, warn = FALSE)
  } else {
    content <- c("# Problems and Issues", "", "## 1. Estimation Tables (`esttab`)", "")
  }
  
  # Find insertion point (after esttab section header)
  esttab_section <- grep("^## 1\\. Estimation Tables", content)
  if (length(esttab_section) == 0) {
    # Add new section
    content <- c(content, "", "## 1. Estimation Tables (`esttab`)", "")
    insert_idx <- length(content)
  } else {
    # Find next section or end of file
    next_section <- grep("^## [2-9]\\.", content[(esttab_section[1]+1):length(content)])
    if (length(next_section) > 0) {
      insert_idx <- esttab_section[1] + next_section[1] - 1
    } else {
      insert_idx <- length(content)
    }
  }
  
  # Generate new issue entries
  new_entries <- character()
  current_num <- existing$max_number
  
  for (error in truly_new) {
    current_num <- current_num + 1
    entry <- generate_issue_entry(error, current_num)
    new_entries <- c(new_entries, entry)
  }
  
  # Insert new entries
  content <- append(content, new_entries, after = insert_idx)
  
  # Write back
  writeLines(content, problems_file)
  
  message(sprintf("Added %d new issue(s) to PROBLEMS.md", length(truly_new)))
  
  # Update error log status
  update_error_status(log_file, truly_new, "DOCUMENTED")
  
  return(length(truly_new))
}

#' Update error status in log file
#' 
#' @param log_file Path to error log
#' @param errors List of errors to update
#' @param new_status New status value
update_error_status <- function(log_file, errors, new_status) {
  log_data <- fromJSON(log_file, flatten = FALSE)
  
  sigs_to_update <- sapply(errors, function(e) e$signature)
  
  for (i in seq_along(log_data$errors)) {
    if (log_data$errors[[i]]$signature %in% sigs_to_update) {
      log_data$errors[[i]]$status <- new_status
    }
  }
  
  write_json(log_data, log_file, pretty = TRUE, auto_unbox = TRUE)
}

#' Mark an issue as resolved in PROBLEMS.md
#' 
#' @param issue_number Issue number to resolve (e.g., "1.5")
#' @param resolution_note Optional note about the fix
#' @return TRUE if successful
resolve_issue <- function(issue_number, resolution_note = NULL) {
  problems_file <- ".opencode/PROBLEMS.md"
  
  if (!file.exists(problems_file)) {
    warning("PROBLEMS.md not found")
    return(FALSE)
  }
  
  content <- readLines(problems_file, warn = FALSE)
  
  # Find the issue
  pattern <- sprintf("^### %s\\.", issue_number)
  issue_line <- grep(pattern, content)
  
  if (length(issue_line) == 0) {
    warning(sprintf("Issue %s not found", issue_number))
    return(FALSE)
  }
  
  # Update status
  status_line <- issue_line[1] + 1
  if (status_line <= length(content)) {
    content[status_line] <- sub("OPEN", "RESOLVED", content[status_line])
    if (!is.null(resolution_note)) {
      content <- append(content, 
        sprintf("**Resolution**: %s (%s)", resolution_note, format(Sys.time(), "%Y-%m-%d")),
        after = status_line)
    }
  }
  
  writeLines(content, problems_file)
  message(sprintf("Marked issue %s as RESOLVED", issue_number))
  return(TRUE)
}
