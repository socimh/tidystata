library(statart)
options(width = 90, cli.num_colors = 1)
cat("SUMMARY ALIASES AND SUM\n")
print(summ(tibble::tibble(x = c(1, 3, NA)), .stat = c("n", "missing", "sum", "p50")))
cat("\nZERO-OBSERVATION SUMMARY\n")
print(summ(tibble::tibble(x = numeric())))
cat("\nCROSS-TABLE CATEGORY MATCHING ROW VARIABLE\n")
d <- tibble::tibble(row = c("A", "A", "B"), col = c("row", "other", "row"))
print(fre2(d, row, col))
cat("\nEMPTY VARIABLE SELECTION\n")
print(tab(d, tidyselect::starts_with("absent")))
cat("\nLIST-COLUMN COUNTS\n")
print(tab(tibble::tibble(value = list(1:2, 1:2, 2:3)), value))
cat("\nSUBSTRING AND ANCHORED SEARCH\n")
d <- tibble::tibble(x1 = 1, x2 = 2, x10 = 3)
print(variables_search(d, "x?"))
print(variables_search(d, "^x?$"))
