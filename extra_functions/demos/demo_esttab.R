# Demo: esttab() function
# Shows actual output of esttab() for regression tables

library(dplyr)
library(lme4)

devtools::load_all(".", quiet = TRUE)

cat("## Example 1: Simple linear regression\n\n")
cat("```r\n")
cat("model <- lm(mpg ~ wt, data = mtcars)\n")
cat("esttab(model)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
model <- lm(mpg ~ wt, data = mtcars)
print(esttab(model))
cat("```\n\n")

cat("## Example 2: Multiple regression\n\n")
cat("```r\n")
cat("model <- lm(mpg ~ wt + hp + cyl, data = mtcars)\n")
cat("esttab(model)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
model <- lm(mpg ~ wt + hp + cyl, data = mtcars)
print(esttab(model))
cat("```\n\n")

cat("## Example 3: Logistic regression (GLM)\n\n")
cat("```r\n")
cat("model <- glm(vs ~ wt + disp, data = mtcars, family = binomial)\n")
cat("esttab(model)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
model <- glm(vs ~ wt + disp, data = mtcars, family = binomial)
print(esttab(model))
cat("```\n\n")

cat("## Example 4: Linear mixed effects (lmer)\n\n")
cat("```r\n")
cat("model <- lmer(Reaction ~ Days + (Days | Subject), sleepstudy)\n")
cat("esttab(model)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
model <- lmer(Reaction ~ Days + (Days | Subject), sleepstudy)
print(esttab(model))
cat("```\n\n")

cat("## Example 5: With custom statistics\n\n")
cat("```r\n")
cat("model <- lm(mpg ~ wt, data = mtcars)\n")
cat("esttab(model, stats = c('n.obs', 'r.squared'))\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
model <- lm(mpg ~ wt, data = mtcars)
print(esttab(model, stats = c("n.obs", "r.squared")))
cat("```\n\n")

cat("## Example 6: With custom format\n\n")
cat("```r\n")
cat("model <- lm(mpg ~ wt, data = mtcars)\n")
cat("esttab(model, format = '{estimate} ({std.error})')\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
model <- lm(mpg ~ wt, data = mtcars)
print(esttab(model, format = "{estimate} ({std.error})"))
cat("```\n\n")

cat("## Example 7: With factor variables\n\n")
cat("```r\n")
cat("mtcars$cyl_f <- factor(mtcars$cyl)\n")
cat("model <- lm(mpg ~ wt + cyl_f, data = mtcars)\n")
cat("esttab(model)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
mtcars$cyl_f <- factor(mtcars$cyl)
model <- lm(mpg ~ wt + cyl_f, data = mtcars)
print(esttab(model))
cat("```\n\n")

cat("## Example 8: With interaction terms\n\n")
cat("```r\n")
cat("model <- lm(mpg ~ wt * hp, data = mtcars)\n")
cat("esttab(model)\n")
cat("```\n\n")
cat("**Output:**\n\n")
cat("```\n")
model <- lm(mpg ~ wt * hp, data = mtcars)
print(esttab(model))
cat("```\n\n")
